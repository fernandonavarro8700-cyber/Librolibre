let currentLang = 'es';

export function setLanguage(lang) {
  currentLang = dict[lang] ? lang : 'es';
}

export function getLanguage() {
  return currentLang;
}

/**
 * Traduce una clave. Soporta variables simples con {placeholder} y una
 * variante "_one"/"_other" según `count` (pluralización básica ES/EN/FR/PT,
 * donde solo el 1 es singular).
 */
export function t(key, vars = {}) {
  let resolvedKey = key;
  if (typeof vars.count === 'number') {
    resolvedKey = `${key}_${vars.count === 1 ? 'one' : 'other'}`;
  }

  const table = dict[currentLang] || dict.es;
  let str = table[resolvedKey] ?? dict.es[resolvedKey] ?? table[key] ?? dict.es[key] ?? key;

  Object.keys(vars).forEach((k) => {
    if (k === 'count') return;
    str = str.replace(`{${k}}`, vars[k]);
  });
  if (typeof vars.count === 'number') {
    str = str.replace('{n}', vars.count);
  }

  return str;
}

/** Recorre el DOM aplicando data-i18n / data-i18n-placeholder / data-i18n-aria. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-tooltip]').forEach((el) => {
    el.setAttribute('data-tooltip', t(el.dataset.i18nTooltip));
  });
}

window.LibroLibreI18n = { t, setLanguage, getLanguage, applyTranslations, LANGUAGES };
export default { t, setLanguage, getLanguage, applyTranslations, LANGUAGES };
